import { test, expect } from '@playwright/test';
import { createInitialState, coachReducer } from '../src/coach-state';
const nav=(page:any,name:string)=>page.getByRole('navigation').getByRole('button',{name,exact:true});
test('period clock, score history and closing preview show recorded figures',async({page})=>{
 let s=createInitialState();
 for(const action of [{type:'toggle-clock',now:1000},{type:'goal',playerId:'p02',now:61000},{type:'phase',now:61000},{type:'phase',now:120000},{type:'away-goal',delta:1,now:150000},{type:'toggle-clock',now:150000}] as const) s=coachReducer(s,action);
 await page.addInitScript(state=>localStorage.setItem('coachmate:v1',JSON.stringify(state)),s);
 await page.goto('/?device=real'); await nav(page,'Live').click();
 await expect(page.locator('.page-title strong')).toHaveText('Live wedstrijd');
 await expect(page.locator('.match-time-totals > div').filter({hasText:'Speeltijd'}).locator('dd')).toHaveText('01:30');
 await expect(page.locator('.period-times')).toContainText('01:00');
 await expect(page.locator('.period-times')).toContainText('00:30');
 await expect(page.getByTestId('goals-for')).toContainText('Mats');
 await expect(page.getByTestId('goals-for')).toContainText('0–1');
 await expect(page.getByTestId('goals-against')).toContainText('1–1');
 await page.getByRole('button',{name:'Wedstrijddata verwerken',exact:true}).click();
 await expect(page.getByRole('dialog').locator('.finish-score')).toContainText('1–1');
 await expect(page.getByRole('dialog').locator('.finish-table > div').filter({hasText:'Mats'})).toHaveText('Mats201');
 await page.getByRole('button',{name:'Sluiten',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
});
test('history page owns entry action, rankings switch and history filters',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/?device=real'); await nav(page,'Statistieken').click();
 await expect(page.getByLabel('Cumulatieve statistieken')).toContainText('660');
 await page.getByText('Ranglijsten',{exact:true}).click(); await page.getByRole('button',{name:'Keeperminuten',exact:true}).click();
 await expect(page.locator('.ranking-list li').first()).toContainText('Daan');
 await expect(page.locator('.stats-fab')).toHaveCount(0);
 await page.getByRole('button',{name:'Bekijk en corrigeer historische wedstrijdgegevens',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 const fab=page.getByRole('button',{name:'Wedstrijd invoeren',exact:true});
 await expect(fab).toBeVisible();
 await fab.click(); await expect(page.getByRole('heading',{name:'Wedstrijdhistorie'})).toBeVisible();
 await expect(page.locator('.entry-save-footer').getByRole('button',{name:'Opslaan',exact:true})).toBeEnabled();
 await nav(page,'Overzicht').click(); await nav(page,'Statistieken').click();
 await page.getByRole('button',{name:'Terug',exact:true}).click();
 await page.getByLabel('Wedstrijdhistorie zoeken').fill('Waterwijk');
 await expect(page.locator('.history-match-list .history-row')).toHaveCount(1);
 await expect(page.locator('.history-match-list .history-row')).toContainText('FC Waterwijk');
});
